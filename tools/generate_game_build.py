"""Regenerate audited executable profiles from the exact recorded input binaries.

From the project root, with Python 3.9+, llvm-objdump on PATH and a build directory:
    python tools/generate_game_build.py <ubisoft-uplay-executable> <steam-executable>

tools/game-builds.json supplies the required input hashes and address mappings.
The output is source/shared/GameBuildAddresses.h. Run the canonical build after
regenerating the table.
"""
import argparse
import hashlib
import json
import re
import struct
import subprocess
import tempfile
from pathlib import Path
from compare_executable_builds import PE


def instruction_prefix(path, base, rva):
    output = subprocess.check_output(['llvm-objdump', '-d', f'--start-address={base+rva:#x}',
                                      f'--stop-address={base+rva+32:#x}', str(path)], text=True, encoding='utf-8', errors='replace')
    result = []
    for line in output.splitlines():
        match = re.match(r'^([0-9a-f]+):\s+((?:[0-9a-f]{2}\s+)+)\s*(\S.*)$', line)
        if not match:
            continue
        raw = bytes.fromhex(match[2])
        asm = match[3].split('#')[0].strip()
        asm = re.sub(r'-?0x[0-9a-f]+\(%rip\)', 'RIP(%rip)', asm)
        if re.match(r'^(?:j\w+|call\w*|loop\w*)\s+0x', asm):
            asm = re.sub(r'0x[0-9a-f]+(?:\s+<[^>]+>)?', 'TARGET', asm)
        result.append((len(raw), asm))
    return result


def safe_signature_length(a, b, left_path, right_path, x, y):
    left = instruction_prefix(left_path, a.base, x)
    right = instruction_prefix(right_path, b.base, y)
    length = 0
    for old, new in zip(left, right):
        if old != new or length + old[0] > 32:
            break
        length += old[0]
    if not length:
        raise ValueError(f'Instruction shape mismatch at {x:#x} -> {y:#x}')
    return length


def generate(left, right, manifest_path, output_path):
    manifest = json.loads(Path(manifest_path).read_text())
    a, b = PE(left), PE(right)
    for pe, expected in zip((a, b), manifest['executables']):
        if hashlib.sha256(pe.data).hexdigest() != expected['sha256']:
            raise ValueError('Executable SHA256 does not match the audited build identity')
    mapping = {int(k, 16): int(v, 16) for k, v in manifest['addresses'].items()}
    if len(set(mapping.values())) != len(mapping):
        raise ValueError('Ambiguous reverse address mapping')
    lines = ['#pragma once', '', '// Generated by tools/generate_game_build.py from tools/game-builds.json.',
             '// Exact byte pairs retain strict hook validation for both executable builds.',
             'namespace GameBuild', '{',
             'struct AddressPair { uintptr_t canonical, alternate; };',
             'static constexpr AddressPair addresses[] = {']
    lines += [f'    {{0x{x:x}, 0x{y:x}}},' for x, y in sorted(mapping.items())]
    lines += ['};', 'static constexpr AddressPair reverseAddresses[] = {']
    lines += [f'    {{0x{x:x}, 0x{y:x}}},' for x, y in sorted(mapping.items(), key=lambda pair: pair[1])]
    lines += ['};', 'struct SignaturePair { uintptr_t canonical; size_t size; uint8_t original[32], alternate[32]; };',
              'static constexpr SignaturePair signatures[] = {']
    count = 0
    # LLVM rejects these executables' oversized TLS directory declaration. Only
    # correct that directory length in disposable inspection copies; code bytes
    # and all signature bytes always come from the authenticated originals.
    build_root = Path('build').resolve()
    with tempfile.TemporaryDirectory(prefix='compat-inspection-', dir=build_root) as directory:
        if not Path(directory).resolve().is_relative_to(build_root):
            raise ValueError('Inspection directory must remain inside build')
        copies = []
        for index, pe in enumerate((a, b)):
            data = bytearray(pe.data)
            struct.pack_into('<I', data, pe.optional + 112 + 9 * 8 + 4, 40)
            path = Path(directory) / f'{index}.bin'
            path.write_bytes(data)
            copies.append(path)
        for x, y in sorted(mapping.items()):
            if not (a.sections[0]['rva'] <= x < a.sections[0]['rva'] + a.sections[0]['size']):
                continue
            original, alternate = a.read(x, 32), b.read(y, 32)
            if original is None or alternate is None:
                raise ValueError(f'Incomplete code signature at {x:x}')
            if original == alternate:
                continue
            size = safe_signature_length(a, b, *copies, x, y)
            if original[:size] == alternate[:size]:
                continue
            as_cpp = lambda data: ','.join(f'0x{byte:02x}' for byte in data)
            lines.append(f'    {{0x{x:x}, {size}, {{{as_cpp(original)}}}, {{{as_cpp(alternate)}}}}},')
            count += 1
    lines += ['};', '}', '']
    Path(output_path).write_text('\n'.join(lines))
    print(f'Generated {len(mapping)} audited address pairs and {count} exact changed signatures')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('left')
    parser.add_argument('right')
    parser.add_argument('--manifest', default='tools/game-builds.json')
    parser.add_argument('--output', default='source/shared/GameBuildAddresses.h')
    args = parser.parse_args()
    generate(args.left, args.right, args.manifest, args.output)
